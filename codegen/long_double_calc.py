"""Write a long double copy of effsource_equatorial_ctx_calc for use as a test reference.

Usage: python long_double_calc.py CTX_SOURCE OUT_SOURCE
"""

import re
import sys

CALC_NAME = "effsource_equatorial_ctx_calc"
REFERENCE_NAME = "effsource_equatorial_ctx_calc_long_double"


def main():
    """Read the context source and write the long double reference."""
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source_path, out_path = sys.argv[1:]
    text = open(source_path).read()
    start = text.index(f"void {CALC_NAME}(")
    brace = text.index("{", start)
    end = text.index("\n}", brace)
    body = text[brace + 1:end]
    body = re.sub(r"\bconst double\b", "const long double", body)
    body = re.sub(r"(^|\n)(\s*)double\b", r"\1\2long double", body)
    for function in ("sin", "cos", "sqrt"):
        body = re.sub(rf"\b{function}\(", f"{function}l(", body)
    with open(out_path, "w") as stream:
        stream.write(
            "/* Generated by codegen/long_double_calc.py from kerr-equatorial-ctx.c. Do not edit. */\n\n"
            "#include <math.h>\n"
            "#include \"effsource_equatorial.h\"\n\n"
            f"void {REFERENCE_NAME}(const struct effsource_equatorial_ctx *ctx, const struct coordinate *x,\n"
            "    long double *PhiS, long double *dPhiS_dx, long double *d2PhiS_dx2, long double *src)\n"
            "{" + body + "\n}\n")


if __name__ == "__main__":
    main()
