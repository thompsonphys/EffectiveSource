#!/usr/bin/env python3
"""Generate phis, calc, phis_m and calc_m for EquatorialCtx from kerr-equatorial-ctx.c."""
from pathlib import Path
import kernelgen as kg

HERE = Path(__file__).resolve().parent
SRC = (HERE.parent.parent / "kerr-equatorial-ctx.c").read_text()
OUT = HERE.parent / "EffSourceEquatorial" / "src" / "_eq_kernels.jl"
CTX = "EquatorialCtx"


def mode_guard(body):
    """Reject negative modes as well as modes above the table range."""
    out, hits = [], 0
    for line in body:
        if line.strip() == "if m > 20":
            line = line.replace("if m > 20", "if m < 0 || m > 20")
            hits += 1
        out.append(line.replace("(m>20)", "(need 0 <= m <= 20)"))
    assert hits == 1, hits
    return out


def gen(name, doc, extra_args, extra_call, setup, ret, marker, post=None):
    return kg.build(SRC, CTX, name, doc, extra_args, extra_call, setup, ret, marker,
                    comp=False, post=post)


parts = [
    gen("phis", "Real-space singular field at `x` (or an `Offset`).", "", "", [], kg.RET_PHIS,
        "void effsource_equatorial_ctx_PhiS(struct"),
    gen("calc", "Singular field, first and second derivatives and effective source; "
        "returns `(PhiS, dPhiS_dx[4], d2PhiS_dx2[10], src)`.", "", "",
        kg.SETUP_CALC, kg.RET_CALC, "void effsource_equatorial_ctx_calc(struct"),
    gen("phis_m", "m-mode singular field (complex), including the phase exp(-i m phi_p).",
        "m::Integer, ", "m, ", kg.SETUP_PHIS_M, kg.RET_PHIS_M,
        "void effsource_equatorial_ctx_PhiS_m(struct", mode_guard),
    gen("calc_m", "m-mode singular field, derivatives and effective source (complex); "
        "returns `(PhiS, dPhiS_dx[4], d2PhiS_dx2[10], src)`.", "m::Integer, ", "m, ",
        kg.SETUP_CALC_M, kg.RET_CALC_M, "void effsource_equatorial_ctx_calc_m(struct", mode_guard),
]

OUT.write_text("# Auto-generated by tools/eq_generate_kernels.py -- do not edit by hand.\n\n"
               + "\n".join(parts) + "\n")
print(f"Wrote {OUT}")
