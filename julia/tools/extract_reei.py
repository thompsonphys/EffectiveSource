#!/usr/bin/env python3
"""Emit the ReEI and ImEI elliptic-integral tables as Float64 values from the C sources and as exact rationals from elliptic_tables_exact.txt."""
import re
import sys
from fractions import Fraction
from math import ulp
from pathlib import Path

DIMS = (21, 2, 5, 27)
EXPECTED = DIMS[0] * DIMS[1] * DIMS[2] * DIMS[3]
INT128 = 2**127

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
SRC_C = REPO / "kerr-circular-ctx.c"
SRC_EQ = REPO / "kerr-equatorial-ctx.c"
EXACT = HERE / "elliptic_tables_exact.txt"
OUT_JL = HERE.parent / "src" / "reei_data.jl"
OUT_IMEI = HERE.parent / "EffSourceEquatorial" / "src" / "imei_data.jl"


def flat(m, i, j, k):
    return ((m * 2 + i) * 5 + j) * 27 + k


def extract(src, name):
    text = src.read_text()
    decl = text.index(f"{name}[21][2][5][27]")
    eq = text.index("=", decl)
    semi = text.index(";", eq)
    body = text[eq + 1 : semi]
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.DOTALL)
    body = re.sub(r"//[^\n]*", " ", body)
    body = body.replace("{", " ").replace("}", " ")
    nums = [float(t) for t in (t.strip() for t in body.split(",")) if t != ""]
    if len(nums) != EXPECTED:
        sys.exit(f"ERROR: parsed {len(nums)} {name} numbers, expected {EXPECTED}")
    return nums


def exact_tables():
    tabs = {"Re": [Fraction(0)] * EXPECTED, "Im": [Fraction(0)] * EXPECTED}
    for line in EXACT.read_text().splitlines():
        tag, m, i, j, k, q = line.split()
        m, i, j, k, q = int(m), int(i), int(j), int(k), Fraction(q)
        if k >= DIMS[3]:
            if q != 0:
                sys.exit(f"ERROR: nonzero {tag}EI[{m}][{i}][{j}][{k}] beyond the C table")
            continue
        tabs[tag][flat(m, i, j, k)] = q
    return tabs


def check(nums, exact, name):
    for n, (x, q) in enumerate(zip(nums, exact)):
        if abs(float(q) - x) > ulp(float(q)):
            sys.exit(f"ERROR: {name} entry {n}: C {x!r} vs exact {q} ({float(q)!r})")
        if abs(q.numerator) >= INT128 or q.denominator >= INT128:
            sys.exit(f"ERROR: {name} entry {n} does not fit Int128: {q}")


def chunks(values):
    return [f"    {', '.join(values[i:i + 8])}," for i in range(0, len(values), 8)]


def emit(nums, exact, name, out_path):
    up, low = name.upper(), name.lower()
    lines = ["# Auto-generated by tools/extract_reei.py -- do not edit by hand.",
             f"# {name}[21][2][5][27] complete-elliptic-integral expansion coefficients,",
             "# flattened in C row-major order (last index k fastest).",
             "",
             f"const {up}_DIMS = {DIMS}",
             f"const {up}_FLAT = Float64["]
    lines += chunks([repr(x) for x in nums])
    lines += ["]",
              "",
              f"# 0-based indices matching the C code: {name}[m][i][j][k].",
              "# Coefficients are returned in type T so they do not promote a",
              "# low-precision working type back up to Float64.",
              f"@inline {low}(::Type{{T}}, m::Integer, i::Integer, j::Integer, k::Integer) where {{T}} =",
              f"    T(@inbounds {up}_FLAT[((m * 2 + i) * 5 + j) * 27 + k + 1])",
              "",
              f"const {up}_NUM = Int128["]
    lines += chunks([str(q.numerator) for q in exact])
    lines += ["]", f"const {up}_DEN = Int128["]
    lines += chunks([str(q.denominator) for q in exact])
    lines += ["]",
              "",
              f"@inline function {low}(::Type{{BigFloat}}, m::Integer, i::Integer, j::Integer, k::Integer)",
              "    n = ((m * 2 + i) * 5 + j) * 27 + k + 1",
              f"    return BigFloat(@inbounds {up}_NUM[n])/BigFloat(@inbounds {up}_DEN[n])",
              "end",
              ""]
    out_path.write_text("\n".join(lines))
    print(f"Wrote {out_path} ({len(nums)} coefficients)")


if __name__ == "__main__":
    exact = exact_tables()
    reei_c = extract(SRC_C, "ReEI")
    if extract(SRC_EQ, "ReEI") != reei_c:
        sys.exit("ERROR: equatorial ReEI differs from circular ReEI")
    imei = extract(SRC_EQ, "ImEI")
    check(reei_c, exact["Re"], "ReEI")
    check(imei, exact["Im"], "ImEI")
    emit(reei_c, exact["Re"], "ReEI", OUT_JL)
    OUT_IMEI.parent.mkdir(parents=True, exist_ok=True)
    emit(imei, exact["Im"], "ImEI", OUT_IMEI)
