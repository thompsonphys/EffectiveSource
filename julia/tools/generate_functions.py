#!/usr/bin/env python3
"""Generate the four transpiled circular kernels into src/_generated_kernels.jl."""
from pathlib import Path
import kernelgen as kg

HERE = Path(__file__).resolve().parent
SRC = (HERE.parent.parent / "kerr-circular-ctx.c").read_text()
OUT = HERE.parent / "src" / "_generated_kernels.jl"
CTX = "EffsourceCtx"

_ELL_E = "ellE = _ellE(sqrt(T(1.0)/(T(1.0)+C1)))"
_ELL_K = "ellK = _ellK(sqrt(T(1.0)/(T(1.0)+C1)))"


def ell_switch(body):
    """Replace the GSL-style K, E pair with the switchable `_ellKE_arg` call."""
    out, i, hits = [], 0, 0
    while i < len(body):
        if body[i].strip() == _ELL_E and i + 1 < len(body) and body[i + 1].strip() == _ELL_K:
            out.append(body[i].replace(_ELL_E, "(ellK, ellE) = _ellKE_arg(C1)"))
            i += 2
            hits += 1
        else:
            out.append(body[i])
            i += 1
    assert hits == 1, hits
    return out


def gen_phis():
    doc = "Real-space singular field PhiS at field point `x` (or `Offset`)."
    return kg.build(SRC, CTX, "phis", doc, "", "", [], kg.RET_PHIS,
                    "void effsource_ctx_PhiS(struct", comp=False)


def gen_calc():
    doc = ("Singular field, its first/second derivatives and the effective source.\n"
           "Returns `(PhiS, dPhiS_dx[4], d2PhiS_dx2[10], src)` with component order\n"
           "(t,r,theta,phi) and (tt,tr,ttheta,tphi,rr,rtheta,rphi,thetatheta,thetaphi,phiphi).\n"
           "`comp=true` sums the source numerator with compensated (Neumaier) summation.")
    return kg.build(SRC, CTX, "calc", doc, "", "", kg.SETUP_CALC, kg.RET_CALC,
                    "void effsource_ctx_calc(struct", comp=True)


def gen_phis_m():
    doc = ("m-mode singular field (complex), including phase exp(-i m phi_p).\n"
           "`comp=true` uses compensated summation for the numerator.")
    return kg.build(SRC, CTX, "phis_m", doc, "m::Integer, ", "m, ", kg.SETUP_PHIS_M, kg.RET_PHIS_M,
                    "void effsource_ctx_PhiS_m(struct", comp=True, post=ell_switch)


def gen_calc_m():
    doc = ("m-mode singular field, derivatives and effective source (all complex).\n"
           "Returns `(PhiS, dPhiS_dx[4], d2PhiS_dx2[10], src)`.\n"
           "`comp=true` uses compensated summation for the numerator and source.")
    return kg.build(SRC, CTX, "calc_m", doc, "m::Integer, ", "m, ", kg.SETUP_CALC_M, kg.RET_CALC_M,
                    "void effsource_ctx_calc_m(struct", comp=True, post=ell_switch)


header = """\
# ============================================================================
# Auto-generated by tools/generate_functions.py from kerr-circular-ctx.c.
# Do not edit by hand -- re-run the generator instead.
# ============================================================================
"""

OUT.write_text(
    header + "\n"
    + gen_phis() + "\n"
    + gen_calc() + "\n"
    + gen_phis_m() + "\n"
    + gen_calc_m() + "\n"
)
print(f"Wrote {OUT}")
