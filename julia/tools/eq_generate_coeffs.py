#!/usr/bin/env python3
"""Generate EquatorialCtx, the interpreted coefficient functions and set_particle! from the equatorial C sources."""
import re
from pathlib import Path
from c2jl import convert_expr

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
OUT = HERE.parent / "EffSourceEquatorial" / "src"
SOURCES = (("coeffs", "kerr-equatorial-coeffs-ctx.c"),
           ("dtcoeffs", "kerr-equatorial-dtcoeffs-ctx.c"),
           ("dttcoeffs", "kerr-equatorial-dttcoeffs-ctx.c"))
INPUTS = ("M", "a", "r", "E", "L", "ur")
STAMP = "# Auto-generated by tools/eq_generate_coeffs.py -- do not edit by hand.\n"

_DECL = re.compile(r"^const double (\w+)\s*=\s*(.*);$")
_STORE = re.compile(r"^ctx->(\w+)\s*=\s*(.*);$")
_IDENT = re.compile(r"[A-Za-z_]\w*")


def header_fields():
    text = (REPO / "effsource_equatorial.h").read_text()
    start = text.index("struct effsource_equatorial_ctx {")
    body = re.sub(r"/\*.*?\*/", " ", text[start:text.index("};", start)], flags=re.S)
    fields = []
    for decl in re.findall(r"\bdouble\s+([^;]*);", body):
        fields += [f.strip() for f in decl.split(",")]
    return fields


def parse(path):
    helpers, stores = [], []
    for line in path.read_text().splitlines():
        s = line.strip()
        m = _DECL.match(s)
        if m:
            if "ctx->" not in m.group(2) and "xp." not in m.group(2):
                helpers.append((m.group(1), convert_expr(m.group(2))))
            continue
        m = _STORE.match(s)
        if m and m.group(1) != "xp":
            stores.append((m.group(1), convert_expr(m.group(2))))
    return helpers, stores


def helper_fn(tag, helpers):
    out = [f"function helpers_{tag}(M::T, a::T, r::T, E::T, L::T, ur::T) where {{T}}"]
    out += [f"    {n} = {e}" for n, e in helpers]
    out.append(f"    return (; {', '.join(INPUTS)}, {', '.join(n for n, _ in helpers)})")
    out.append("end\n")
    return "\n".join(out)


def coeff_fn(name, expr, known):
    used = sorted(set(_IDENT.findall(expr)) & known)
    out = [f"function c_{name}(h::NamedTuple)"]
    if used:
        out.append(f"    (; {', '.join(used)}) = h")
    out.append("    T = typeof(h.r)")
    out.append(f"    return {expr}")
    out.append("end\n")
    return "\n".join(out)


def struct_jl(fields):
    lines = [STAMP,
             '"""Effective-source context for eccentric equatorial Kerr orbits, generic over the numeric type T."""',
             "mutable struct EquatorialCtx{T}",
             "    M::T", "    a::T", "    xp::Coordinate{T}", "    ell_from_complement::Bool"]
    lines += [f"    {f}::T" for f in fields]
    lines += ["", "    EquatorialCtx{T}() where {T} = new{T}()", "end", "",
              "Base.eltype(::EquatorialCtx{T}) where {T} = T", "",
              f"const COEFF_FIELDS = ({', '.join(':' + f for f in fields)},)", "",
              '"""Allocate a context for black-hole mass `M` and spin `a`."""',
              "function effsource_equatorial_create(M, a; ell_from_complement::Bool=false)",
              "    T0 = promote_type(typeof(M), typeof(a))",
              "    T = T0 <: Integer ? Float64 : T0",
              "    ctx = EquatorialCtx{T}()",
              "    ctx.M = T(M)",
              "    ctx.a = T(a)",
              "    ctx.xp = Coordinate{T}()",
              "    ctx.ell_from_complement = ell_from_complement",
              "    return ctx",
              "end", ""]
    return "\n".join(lines)


def set_particle_jl(fields):
    lines = [STAMP,
             '"""Place the particle at `x_p` with constants `E`, `L` and radial velocity `ur`; '
             'coefficients are evaluated in precision `setup` and stored in the context type."""',
             "function set_particle!(ctx::EquatorialCtx{Tc}, x_p::Coordinate{Tc}, E, L, ur;",
             "                       setup::Type{T}=Tc) where {Tc,T}",
             "    ctx.xp = x_p",
             "    v = _Coefficients.coefficients(T(ctx.M), T(ctx.a), T(x_p.r), T(E), T(L), T(ur))"]
    lines += [f"    ctx.{f} = Tc(v.{f})" for f in fields]
    lines += ["    return ctx", "end", ""]
    return "\n".join(lines)


def main():
    fields = [f for f in header_fields() if f not in ("M", "a")]
    parts, order = [STAMP], []
    for tag, fname in SOURCES:
        helpers, stores = parse(REPO / fname)
        known = set(INPUTS) | {n for n, _ in helpers}
        parts.append(helper_fn(tag, helpers))
        parts += [coeff_fn(n, e, known) for n, e in stores]
        order += [(tag, n) for n, _ in stores]
    assigned = [n for _, n in order]
    assert len(assigned) == len(set(assigned)), "duplicate coefficient assignment"
    assert set(assigned) == set(fields), set(assigned) ^ set(fields)
    calls = ",\n        ".join(f"{n} = c_{n}(h_{tag})" for tag, n in order)
    parts.append(
        "function coefficients(M::T, a::T, r::T, E::T, L::T, ur::T) where {T}\n"
        + "".join(f"    h_{tag} = helpers_{tag}(M, a, r, E, L, ur)\n" for tag, _ in SOURCES)
        + f"    return (; {calls})\nend\n")
    (OUT / "_eq_coeffs.jl").write_text("\n".join(parts))
    (OUT / "_eq_ctx_struct.jl").write_text(struct_jl(fields))
    (OUT / "_eq_set_particle.jl").write_text(set_particle_jl(fields))
    print(f"Wrote equatorial context, coefficients and set_particle! ({len(fields)} fields)")


if __name__ == "__main__":
    main()
